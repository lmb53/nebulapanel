#!/usr/bin/env node
/**
 * Build panel/assets/vendor/lucide-subset.js: only the Lucide icons the panel
 * references, plus a small createIcons() compatible with the way the panel
 * uses Lucide. The full library (~400 KB) stays vendored as a fallback that
 * app.js loads automatically if a page ever shows an icon missing here.
 *
 *   node tools/build-icons.js        (re-run after adding icons; CI checks it)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', 'panel');
const full = path.join(root, 'assets/vendor/lucide-1.8.0.min.js');
const out = path.join(root, 'assets/vendor/lucide-subset.js');
const lucide = require(full);

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const files = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (!['vendor', 'data'].includes(entry.name)) walk(p); }
    else if (/\.(php|js)$/.test(entry.name)) files.push(p);
  }
};
walk(root);

// Any quoted kebab-case token that is a Lucide icon name counts as used: the
// panel builds icon names from PHP arrays, JSON and JS strings alike.
const used = new Set();
for (const file of files) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/["'`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`]/g)) {
    if (lucide.icons[pascal(m[1])]) used.add(m[1]);
  }
  for (const m of text.matchAll(/data-lucide="([a-z0-9-]+)"/g)) {
    if (lucide.icons[pascal(m[1])]) used.add(m[1]);
  }
}
const names = [...used].sort();
const icons = {};
for (const name of names) icons[name] = lucide.icons[pascal(name)];

const banner = `/**
 * @license lucide v1.8.0 - ISC (icon data). Subset generated by tools/build-icons.js
 * from lucide-1.8.0.min.js: ${names.length} of ${Object.keys(lucide.icons).length} icons. Do not edit by hand.
 */`;
const runtime = `(function () {
  var ICONS = ${JSON.stringify(icons)};
  var NS = 'http://www.w3.org/2000/svg';
  var self = document.currentScript && document.currentScript.src;
  var fullUrl = self ? self.replace(/lucide-subset\\.js(\\?.*)?$/, 'lucide-1.8.0.min.js') : '';
  var loadingFull = false;
  // An icon missing from the subset (a name built at runtime) loads the full
  // library once, which then replaces this one and draws what is left.
  function loadFull() {
    if (loadingFull || !fullUrl) return;
    loadingFull = true;
    var s = document.createElement('script');
    s.src = fullUrl;
    s.onload = function () { if (window.lucide && !window.lucide.subset) window.lucide.createIcons(); };
    document.head.appendChild(s);
  }
  var BASE = { xmlns: NS, width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor',
    'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  function build(tag, attrs, children) {
    var el = document.createElementNS(NS, tag);
    Object.keys(attrs).forEach(function (k) { el.setAttribute(k, String(attrs[k])); });
    (children || []).forEach(function (c) { el.appendChild(build(c[0], c[1], c[2])); });
    return el;
  }
  function createIcons(opts) {
    opts = opts || {};
    var attr = opts.nameAttr || 'data-lucide';
    var root = opts.root || document;
    var missing = [];
    root.querySelectorAll('[' + attr + ']').forEach(function (el) {
      var name = el.getAttribute(attr);
      var node = ICONS[name];
      if (!node) { missing.push(name); return; }
      var attrs = Object.assign({}, BASE, opts.attrs || {});
      var cls = ['lucide', 'lucide-' + name];
      Array.prototype.forEach.call(el.attributes, function (a) {
        if (a.name === attr) return;
        if (a.name === 'class') { cls = cls.concat(a.value.split(/\\s+/).filter(Boolean)); return; }
        attrs[a.name] = a.value;
      });
      attrs['class'] = cls.filter(function (c, i, all) { return all.indexOf(c) === i; }).join(' ');
      if (!Object.keys(attrs).some(function (k) { return k.indexOf('aria-') === 0 || k === 'role' || k === 'title'; })) {
        attrs['aria-hidden'] = 'true';
      }
      var svg = build('svg', attrs, node);
      if (el.parentNode) el.parentNode.replaceChild(svg, el);
    });
    if (missing.length) loadFull();
    return missing;
  }
  window.lucide = { createIcons: createIcons, icons: ICONS, subset: true };
})();
`;
fs.writeFileSync(out, banner + '\n' + runtime);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${names.length} icons, ${fs.statSync(out).size} bytes`);
